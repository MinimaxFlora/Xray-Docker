write_link_and_info() {
    _path_enc=$(printf '%s' "$XPATH" | sed 's|/|%2F|g')
    _spx_enc=$(printf '%s' "$SPX" | sed 's|/|%2F|g')
    _name_enc=$(printf '%s' "$NODE_NAME" | sed 's| |%20|g')
    # IPv6 literals must be bracketed inside a URI
    _link_addr="$ADDR"
    case "$ADDR" in
        *:*) _link_addr="[$ADDR]" ;;
    esac
    LINK="vless://$UUID@$_link_addr:$PUBLIC_PORT?encryption=$ENC&flow=xtls-rprx-vision&security=reality&sni=$SNI&fp=chrome&pbk=$PUB&sid=$SID&spx=$_spx_enc&type=xhttp&mode=auto&path=$_path_enc#$_name_enc"
    printf '%s\n' "$LINK" > "$LINK_FILE"

    cat > "$INFO_FILE" <<EOF
Xray node: XHTTP + VLESS Encryption (ML-KEM-768) + Vision + REALITY
generated: $(date -u '+%Y-%m-%d %H:%M:%SZ')

address    : $ADDR
port       : $PUBLIC_PORT
uuid       : $UUID
sni        : $SNI
publicKey  : $PUB
shortId    : $SID
path       : $XPATH
mode       : auto
flow       : xtls-rprx-vision
spiderX    : $SPX
encryption : $ENC

How to use:
  1) copy the link below, in v2rayN press Ctrl+V (import from clipboard)
  2) or run an Xray client with: $CLIENT_JSON
EOF
}

validate() {
    # xray prints config errors on stdout, so merge both streams
    if ! "$XRAY_BIN" run -test -c "$SERVER_JSON" >"$DATA_DIR/.validate.err" 2>&1; then
        log "server.json did not pass 'xray run -test':"
        sed 's/^/  /' "$DATA_DIR/.validate.err" >&2 || true
        die "invalid server config, refusing to start"
    fi
    if ! "$XRAY_BIN" run -test -c "$CLIENT_JSON" >"$DATA_DIR/.validate.err" 2>&1; then
        log "client.json did not pass 'xray run -test' (server can still run):"
        sed 's/^/  /' "$DATA_DIR/.validate.err" >&2 || true
    fi
    rm -f "$DATA_DIR/.validate.err"
}

# ----------------------------------------------------------------------------- main
command -v "$XRAY_BIN" >/dev/null 2>&1 || die "xray binary not found in PATH ($XRAY_BIN)"
mkdir -p "$DATA_DIR"

load_or_gen_secrets
resolve_addr
render_server
render_client
write_link_and_info
validate

log "node        : $NODE_NAME ($SNI -> $ADDR:$PUBLIC_PORT)"
log "node link   : $LINK_FILE"
log "client conf : $CLIENT_JSON   (socks 127.0.0.1:10808 / http 127.0.0.1:10809)"
log "server conf : $SERVER_JSON   (managed automatically, no need to touch)"
printf '\n%s\n\n' "$LINK"
if command -v qrencode >/dev/null 2>&1; then
    qrencode -t ANSIUTF8 -m 1 "$LINK" 2>/dev/null || true
    qrencode -o "$DATA_DIR/qr-vless.png" -s 4 -m 1 "$LINK" 2>/dev/null \
        && log "qr code    : $DATA_DIR/qr-vless.png"
    printf '\n'
fi

if [ "$MODE" = "keygen" ]; then
    log "keygen finished, server not started"
    exit 0
fi

if [ "$REGEN" = "1" ]; then
    log "WARN: REGEN=1 is still set in .env, every restart will rotate all keys."
    log "WARN: set REGEN=0 now, or run: docker compose run --rm xray keygen --force"
fi

log "starting xray ..."
exec "$XRAY_BIN" run -c "$SERVER_JSON"

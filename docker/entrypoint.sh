#!/bin/sh
# =============================================================================
#  One-click Xray node:
#      XHTTP (transport) + REALITY (security) + VLESS Encryption (ML-KEM-768)
#      + XTLS Vision (flow=xtls-rprx-vision)
#
#  Behaviour
#    * first start  : generate UUID / x25519 keypair / shortId / vlessenc pair
#                     and persist them in $DATA_DIR/keys.env (0600)
#    * every start   : re-render server.json, the vless:// link and a human
#                     readable summary from keys.env + env vars
#    * sub commands  : entrypoint.sh keygen [--force]   # keys only, no server
#
#  Env vars (all optional)
#    LISTEN_PORT   port xray listens on inside the container     (default 443)
#    PUBLIC_PORT   port reachable from outside, used in the link (default 443)
#    SNI           camouflage site / REALITY target host   (default www.lovelive-anime.jp)
#    SERVER_ADDR   public IP or domain of the VPS, empty = auto detect
#    NODE_NAME     node name shown in the client                (ASCII only)
#    REGEN         1 = throw the old keys away on this start
# =============================================================================
set -eu
umask 022

DATA_DIR="${DATA_DIR:-/data}"
XRAY_BIN="${XRAY_BIN:-xray}"
LISTEN_PORT="${LISTEN_PORT:-443}"
PUBLIC_PORT="${PUBLIC_PORT:-443}"
SNI="${SNI:-www.lovelive-anime.jp}"
SERVER_ADDR="${SERVER_ADDR:-}"
NODE_NAME="${NODE_NAME:-XHTTP-Reality-PQ}"
REGEN="${REGEN:-0}"

KEYS_FILE="$DATA_DIR/keys.env"
SERVER_JSON="$DATA_DIR/server.json"
CLIENT_JSON="$DATA_DIR/client.json"
LINK_FILE="$DATA_DIR/vless-link.txt"
INFO_FILE="$DATA_DIR/connection-info.txt"

MODE="${1:-run}"
FORCE=0
if [ "${2:-}" = "--force" ]; then FORCE=1; fi

log()  { printf '[entrypoint] %s\n' "$*"; }
die()  { printf '[entrypoint] ERROR: %s\n' "$*" >&2; exit 1; }

# ----------------------------------------------------------------------------- helpers
rand_hex() { # $1 = how many hex chars (even number), derived from a fresh v4 uuid
    "$XRAY_BIN" uuid | tr -d '-' | cut -c1-"$1"
}

parse_x25519() { # reads "PrivateKey: ..." / "Password (PublicKey): ..." of any recent core
    sed -n 's/^[Pp]rivate[[:space:]]*[Kk]ey:[[:space:]]*//p' | head -n 1
}

parse_x25519_pub() {
    sed -n -e 's/^[Pp]assword[[:space:]]*([Pp]ublic[[:space:]]*[Kk]ey):[[:space:]]*//p' \
           -e 's/^[Pp]ublic[[:space:]]*[Kk]ey:[[:space:]]*//p' | head -n 1
}

gen_secrets() {
    log "generating a fresh key set with: $("$XRAY_BIN" version | head -n 1)"

    UUID=$("$XRAY_BIN" uuid) || die "'xray uuid' failed"
    # REALITY shortId: 8 random bytes -> 16 hex chars (must be even, <= 16)
    SID=$(rand_hex 16) || die "shortId generation failed"
    # unguessable XHTTP path, looks like a normal api route
    XPATH="/$(rand_hex 12)" || die "path generation failed"
    SPX="/"

    _x=$("$XRAY_BIN" x25519) || die "'xray x25519' failed"
    PRIV=$(printf '%s\n' "$_x" | parse_x25519)
    PUB=$(printf '%s\n' "$_x" | parse_x25519_pub)
    [ -n "$PRIV" ] && [ -n "$PUB" ] || die "cannot parse 'xray x25519' output (core too old?)"

    # VLESS Encryption: official helper prints two pairs, we take the
    # "Authentication: ML-KEM-768" one, i.e. the post-quantum one.
    _v=$("$XRAY_BIN" vlessenc) || die "'xray vlessenc' failed"
    DEC=$(printf '%s\n' "$_v" | awk '
        /Authentication: ML-KEM-768/ { f = 1 }
        f && /"decryption"/ { sub(/^.*"decryption"[[:space:]]*:[[:space:]]*"/, ""); sub(/"$/, ""); print; exit }')
    ENC=$(printf '%s\n' "$_v" | awk '
        /Authentication: ML-KEM-768/ { f = 1 }
        f && /"encryption"/ { sub(/^.*"encryption"[[:space:]]*:[[:space:]]*"/, ""); sub(/"$/, ""); print; exit }')
    [ -n "$DEC" ] && [ -n "$ENC" ] || die "'xray vlessenc' gave no ML-KEM-768 pair (need core >= 25.10)"

    cat > "$KEYS_FILE" <<EOF
# generated by entrypoint.sh - DO NOT EDIT, DO NOT SHARE, BACK THIS FILE UP
UUID='$UUID'
SID='$SID'
XPATH='$XPATH'
SPX='$SPX'
PRIV='$PRIV'
PUB='$PUB'
DEC='$DEC'
ENC='$ENC'
EOF
    chmod 600 "$KEYS_FILE"
    log "secrets written to $KEYS_FILE"
}

load_or_gen_secrets() {
    if [ -f "$KEYS_FILE" ] && [ "$REGEN" != "1" ] && [ "$FORCE" != "1" ]; then
        log "reusing secrets from $KEYS_FILE"
        # shellcheck disable=SC1090
        . "$KEYS_FILE"
        return
    fi
    if [ -f "$KEYS_FILE" ]; then
        log "REGEN/--force requested, rotating all keys (old clients will stop working)"
        mv -f "$KEYS_FILE" "$KEYS_FILE.bak.$(date +%Y%m%d%H%M%S)" 2>/dev/null || rm -f "$KEYS_FILE"
    fi
    gen_secrets
}

resolve_addr() {
    if [ -n "$SERVER_ADDR" ]; then
        ADDR="$SERVER_ADDR"
        return 0
    fi
    for _u in "https://api.ipify.org" "https://ifconfig.me/ip" "https://ipinfo.io/ip"; do
        _ip=$(wget -qO- -T 5 "$_u" 2>/dev/null | tr -d '[:space:]') || true
        case "$_ip" in
            ""|*[!0-9a-fA-F:.]*) continue ;;
            *) ADDR="$_ip"; log "detected public address: $ADDR"; return 0 ;;
        esac
    done
    ADDR="YOUR_SERVER_IP"
    log "WARN: public address unknown, set SERVER_ADDR in .env (link will use a placeholder)"
}

